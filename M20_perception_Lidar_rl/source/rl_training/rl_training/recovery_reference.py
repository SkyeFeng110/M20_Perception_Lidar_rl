"""Scene-labeled MuJoCo replay and selective policy retention for Recovery."""

import hashlib
import json
from pathlib import Path

import numpy as np
import torch


FLAT = 0
ASCENT = 1
SCENES = {FLAT, ASCENT}
PHASES = {1, 2, 3}  # policy idle, moving, after motion
FRONT_SWING = (1, 2, 4, 5)
ALL_LEG_SWING = (1, 2, 4, 5, 7, 8, 10, 11)


def mean_reversal_loss(actions, stair):
    """Bounded, differentiable chatter cost on 3 deterministic policy outputs.

    Fixed Gaussian exploration is excluded. Monotonic lifts and a constant
    wheel command cost zero regardless of amplitude. Slow gait reversals below
    .02 raw action/tick also cost zero; sagittal stair motions get relief.
    """
    previous, delta = actions[1]-actions[0], actions[2]-actions[1]
    magnitude = (torch.minimum(previous.abs(), delta.abs())-.02).clamp_min(0)
    scale = actions.new_tensor([.25]*12+[.5]*4)
    energy = (magnitude/scale).square()
    weights = torch.ones_like(delta)
    weights[:, list(ALL_LEG_SWING)] = torch.where(stair[:, None], .2, 1.)
    return (energy/(1+energy)*(previous*delta < 0)*weights).mean()


def valid_quiet_triplets(dones):
    """(final time, env) indices with no reset in either intervening step."""
    d = dones.squeeze(-1).bool()
    valid = ~(d[:-2] | d[1:-1])
    time, env = valid.nonzero(as_tuple=True)
    return torch.stack((time+2, env), 1)


def load_labeled_replay(path, source_sha256=None):
    path = Path(path)
    metadata = json.loads(path.with_suffix('.json').read_text())
    if metadata.get('schema_version') != 2:
        raise ValueError('Recovery requires replay schema version 2 with physical scene labels')
    if metadata.get('replay_sha256') != hashlib.sha256(path.read_bytes()).hexdigest():
        raise ValueError('Recovery replay metadata hash mismatch')
    if source_sha256 is not None and metadata.get('source_sha256') != source_sha256:
        raise ValueError('Recovery replay was not generated by the frozen teacher checkpoint')
    with np.load(path, allow_pickle=False) as data:
        required = {"observation", "scene", "phase", "case_id"}
        if not required.issubset(data.files):
            raise ValueError("Recovery replay needs physical scene, phase and case labels; regenerate v2 replay")
        obs = data["observation"].copy()
        scene = data["scene"].copy()
        phase = data["phase"].copy()
        case_id = data["case_id"].copy()
    count = len(obs)
    if obs.dtype != np.float32 or obs.shape != (count, 63) or not count or not np.isfinite(obs).all():
        raise ValueError("Recovery replay needs finite float32 N x 63 observations")
    if any(x.shape != (count,) or x.dtype.kind not in "iu" for x in (scene, phase, case_id)):
        raise ValueError("Recovery replay labels must be integer vectors aligned to observations")
    if not set(np.unique(scene)).issubset(SCENES) or not set(np.unique(phase)).issubset(PHASES):
        raise ValueError("Recovery replay has unsupported scene or policy phase")
    if len(np.unique(case_id)) < 2 or any(not (scene == key).any() for key in SCENES):
        raise ValueError("Recovery replay must contain distinct flat and ascent physical cases")
    if count != metadata.get('samples'):
        raise ValueError('Recovery replay metadata sample count mismatch')
    return obs, scene.astype(np.int64), phase.astype(np.int64), case_id.astype(np.int64)


def reference_anchor_loss(predicted, target, observations, scene, front_weight, weight,
                          flat_leg_weight=.04, flat_wheel_differential_weight=.08,
                          ascent_other_weight=.35, tolerance=.05, physical_ascent=False,
                          ascent_wheel_differential_weight=1., leg_scale=None, wheel_scale=None):
    """Keep shared drive but permit scene-specific correction of defective actions."""
    if predicted.shape != target.shape or predicted.ndim != 2 or predicted.shape[1] != 16:
        raise ValueError("Recovery reference actions must be matching N x 16 tensors")
    if observations.shape != (len(predicted), 63) or scene.shape != (len(predicted),):
        raise ValueError("Recovery reference observations and physical labels must align")
    # Labels were validated on CPU in load_labeled_replay before transfer.
    # Rechecking immutable replay labels here would synchronize each CUDA batch.
    flat = scene == FLAT
    ascent_visible = ((observations[:, 57] > .5) & (observations[:, 58] > 0)) | (
        (observations[:, 60] > .5) & (observations[:, 61] > 0))
    on_stairs = (scene == ASCENT) & (ascent_visible | physical_ascent)
    weights = torch.ones_like(predicted[:, :12])
    weights[:, list(FRONT_SWING)] = torch.where(on_stairs[:, None], front_weight, 1.)
    weights[:, list(ALL_LEG_SWING)] = torch.where(flat[:, None], flat_leg_weight,
        weights[:, list(ALL_LEG_SWING)])
    for index in (7, 8, 10, 11):
        weights[:, index] = torch.where(on_stairs, ascent_other_weight, weights[:, index])
    delta = predicted - target.detach()
    leg_error = (delta[:, :12].abs() - tolerance).clamp_min(0).square()
    wheel_delta = delta[:, 12:]
    common = wheel_delta.mean(1, keepdim=True)
    differential = wheel_delta - common
    wheel_error = (wheel_delta.abs() - tolerance).clamp_min(0).square()
    flat_wheel_error = (common.abs() - tolerance).clamp_min(0).square().expand_as(wheel_delta)
    flat_wheel_error = flat_wheel_error + flat_wheel_differential_weight * (
        differential.abs() - tolerance).clamp_min(0).square()
    wheel_error = torch.where(flat[:, None], flat_wheel_error, wheel_error)
    if physical_ascent:
        ascent_wheel_error = (common.abs()-tolerance).clamp_min(0).square().expand_as(wheel_delta)
        ascent_wheel_error = ascent_wheel_error + ascent_wheel_differential_weight * (
            differential.abs()-tolerance).clamp_min(0).square()
        wheel_error = torch.where((scene == ASCENT)[:, None], ascent_wheel_error, wheel_error)
    if leg_scale is not None:
        leg_error = leg_error * leg_scale
    if wheel_scale is not None:
        wheel_error = wheel_error * wheel_scale
    return weight * (leg_error * weights).sum(1).add(wheel_error.sum(1)).mean() / 16.
